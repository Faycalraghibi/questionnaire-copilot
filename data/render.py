"""Render three Markdown policies to PDF or DOCX so every import path is exercised.

Sources: data/policies_src/*.md. Outputs go to data/policies/ with a manifest.yaml that carries the
version and effective date (PDF and DOCX files have no front matter, decision D5).

Usage: uv run python -m data.render
"""

from __future__ import annotations

import datetime as dt
from pathlib import Path
from xml.sax.saxutils import escape

import yaml
from docx import Document
from reportlab import rl_config
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.lib.units import cm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer

from qc.markdown import PolicyDoc, parse_policy

DATA = Path(__file__).parent
SRC_DIR = DATA / "policies_src"
OUT_DIR = DATA / "policies"
MANIFEST = OUT_DIR / "manifest.yaml"

# Decision D5: incident-response and business-continuity as PDF, vendor-management as DOCX.
FORMATS = {
    "incident-response": "pdf",
    "business-continuity": "pdf",
    "vendor-management": "docx",
}

rl_config.invariant = 1  # stable PDF output (no timestamps or random ids)


def _subtitle(doc: PolicyDoc) -> str:
    return f"Northbeam Cloud. Version {doc.meta['version']}, effective {doc.meta['effective_date']}"


def render_pdf(doc: PolicyDoc, path: Path) -> None:
    styles = getSampleStyleSheet()
    story = [
        Paragraph(escape(doc.title), styles["Title"]),
        Paragraph(escape(_subtitle(doc)), styles["Italic"]),
        Spacer(1, 0.4 * cm),
    ]
    for para in doc.preamble:
        story.append(Paragraph(escape(para), styles["BodyText"]))
    for name, paras in doc.sections:
        story.append(Paragraph(escape(name), styles["Heading2"]))
        for para in paras:
            story.append(Paragraph(escape(para), styles["BodyText"]))
    pdf = SimpleDocTemplate(
        str(path),
        pagesize=A4,
        title=doc.title,
        author="Northbeam Cloud",
        leftMargin=2.2 * cm,
        rightMargin=2.2 * cm,
    )
    pdf.build(story)


def render_docx(doc: PolicyDoc, path: Path) -> None:
    out = Document()
    out.add_heading(doc.title, level=0)
    out.add_paragraph().add_run(_subtitle(doc)).italic = True
    for para in doc.preamble:
        out.add_paragraph(para)
    for name, paras in doc.sections:
        out.add_heading(name, level=1)
        for para in paras:
            out.add_paragraph(para)
    props = out.core_properties
    props.title = doc.title
    props.author = "Northbeam Cloud"
    fixed = dt.datetime.combine(doc.meta["effective_date"], dt.time())
    props.created = fixed
    props.modified = fixed
    out.save(str(path))


def render_all(src_dir: Path = SRC_DIR, out_dir: Path = OUT_DIR) -> list[dict]:
    out_dir.mkdir(parents=True, exist_ok=True)
    manifest = []
    for src in sorted(src_dir.glob("*.md")):
        doc = parse_policy(src.read_text(encoding="utf-8"))
        policy_id = doc.meta["policy_id"]
        fmt = FORMATS[policy_id]
        target = out_dir / f"{src.stem}.{fmt}"
        (render_pdf if fmt == "pdf" else render_docx)(doc, target)
        manifest.append(
            {
                "file": target.name,
                "policy_id": policy_id,
                "title": doc.title,
                "version": int(doc.meta["version"]),
                "effective_date": str(doc.meta["effective_date"]),
            }
        )
    (out_dir / MANIFEST.name).write_text(
        "# Generated by data/render.py. Metadata for policy files without front matter.\n"
        + yaml.safe_dump(manifest, sort_keys=False),
        encoding="utf-8",
    )
    return manifest


if __name__ == "__main__":
    for entry in render_all():
        print(f"rendered {entry['file']}")
